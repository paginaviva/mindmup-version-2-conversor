/**
 * @module layer4-styler
 * Layer 4: apply visual styles to every node from attributes[].
 *
 * Responsibilities:
 * 1. Create a Map indexed by node_id for attributes (O(1) lookup).
 * 2. Walk the tree recursively and apply styles to every node.
 * 3. Extract backgroundColor from attrs.value?.style?.backgroundColor.
 * 4. Keep the stickers attached by Layer 3 (node.stickers); if the node does
 *    not have them, use the attrs.raw_attributes?.stickers fallback.
 * 5. Keep the icons attached by Layer 3 (node.icons); if the node does not have
 *    them, use the attrs.raw_attributes?.icon fallback (a single-element array).
 * 6. Expose the attachment metadata (node.attachment) from
 *    attrs.value?.attachment (name, contentType, size) when present; otherwise
 *    node.attachment = null.
 * 7. Classify each attachment as text or binary (node.attachment.isBinary) with
 *    the general isTextAttachment() function (exported): a contentType with a
 *    'text/' prefix or a textual extension means text; otherwise binary.
 * 8. Nodes without attributes receive default values (null, empty array).
 * 9. Return the tree with resolved visual properties.
 *
 * Principle: this function MUTATES the input tree (every node receives style{},
 * stickers[], icons[] and attachment), but it does NOT mutate the original JSON
 * objects: node.attachment is a copy with the isBinary property added.
 *
 * Every tree node receives four new properties: style{}, stickers[], icons[]
 * and attachment (Object|null).
 *
 * Stickers attached by Layer 3 are objects from the JSON stickers collection
 * (with emoji_code and emoji_display fields); the raw_attributes fallback is an
 * array of strings in "emoji:XXXX" format (for example "emoji:1F5FA"). Both
 * formats are converted to Unicode emojis in Layer 5 (Renderer).
 *
 * Complexity: O(n), where n is the number of tree nodes.
 */

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/**
 * Applies visual styles to every tree node from the attributes[] collection.
 *
 * Receives the tree with attached data (generated by Layer 3) and the attributes
 * collection from the CMJN JSON document. It builds a Map indexed by node_id for
 * O(1) lookup and walks the tree recursively, applying backgroundColor, stickers
 * and icons to every node.
 *
 * Stickers and icons attached by Layer 3 (node.stickers / node.icons) are kept
 * as-is to avoid duplication. Only when the node does not have them is the
 * attrs.raw_attributes fallback used (stickers as an array of "emoji:XXXX"
 * codes, icon as a single object wrapped in a one-element array).
 *
 * Uses optional chaining (?.) for safe access to nested properties. Nodes
 * without attributes receive style.backgroundColor: null, stickers: [] and
 * icons: [].
 *
 * @param {Array<Object>} tree - Tree with attached data (from Layer 3). Every
 *   node must have node_id, children[], notes[], externalRefs[] and links[].
 * @param {Array<Object>} attributes - Attributes collection from the CMJN JSON
 *   document. Every attribute must have node_id, value? and raw_attributes?.
 * @returns {Array<Object>} Tree with visual properties. Every node now has:
 *   - style: { backgroundColor: string | null }
 *   - stickers: Array<string|Object> ("emoji:XXXX" format or objects from the
 *     stickers collection; may be empty)
 *   - icons: Array<Object> (icons with url, width, height and position; may be
 *     empty)
 *   - attachment: Object|null (attachment metadata: name, contentType, size and
 *     isBinary; null when the node has no attachment). isBinary is true for
 *     binary attachments (not displayable as text) and false for text, computed
 *     with isTextAttachment().
 *
 * @example
 * const tree = [{ node_id: 'a', children: [{ node_id: 'b', children: [] }] }];
 * const attributes = [{
 *   node_id: 'a',
 *   value: {
 *     style: { backgroundColor: '#FFCC99' },
 *     attachment: { name: 'note.txt', contentType: 'text/plain', size: 42 }
 *   },
 *   raw_attributes: { stickers: ['emoji:1F5FA'], icon: { url: 'data:...', width: 32 } }
 * }];
 * const result = applyStyles(tree, attributes);
 * // result[0].style = { backgroundColor: '#FFCC99' }
 * // result[0].stickers = ['emoji:1F5FA']
 * // result[0].icons = [{ url: 'data:...', width: 32 }]
 * // result[0].attachment = { name: 'note.txt', contentType: 'text/plain', size: 42, isBinary: false }
 * // result[0].children[0].style = { backgroundColor: null }
 * // result[0].children[0].stickers = []
 * // result[0].children[0].icons = []
 * // result[0].children[0].attachment = null
 */
export function applyStyles(tree, attributes) {
  // Map for O(1) lookup by node_id.

  /** @type {Map<string, Object>} */
  const attrsMap = new Map();
  for (const attr of (attributes || [])) {
    attrsMap.set(attr.node_id, attr);
  }

  // Walk the tree recursively and apply styles to every node.
  function traverse(node) {
    const attrs = attrsMap.get(node.node_id);

    if (attrs) {
      // Background color from value.style.backgroundColor (optional chaining).
      node.style = {
        backgroundColor: attrs.value?.style?.backgroundColor || null
      };
      // Stickers: keep the ones attached by Layer 3 (avoids duplication); if
      // there are none, fall back to raw_attributes.stickers.
      node.stickers = (Array.isArray(node.stickers) && node.stickers.length > 0)
        ? node.stickers
        : (attrs.raw_attributes?.stickers || []);
      // Icons: keep the ones attached by Layer 3; if there are none, fall back
      // to raw_attributes.icon as a one-element array.
      node.icons = (Array.isArray(node.icons) && node.icons.length > 0)
        ? node.icons
        : (attrs.raw_attributes?.icon ? [attrs.raw_attributes.icon] : []);
      // Attachment: metadata from value.attachment (name, contentType, size)
      // plus the text/binary classification (isBinary) computed with
      // isTextAttachment(). A copy of the object is created so the original
      // JSON is not mutated. The base64 content does not travel here (it stays
      // in raw_attributes and is transmitted through MMUP_DATA.attachments).
      const rawAttachment = attrs.value?.attachment || null;
      node.attachment = rawAttachment
        ? { ...rawAttachment, isBinary: !isTextAttachment(rawAttachment) }
        : null;
    } else {
      // Default values for nodes without attributes.
      node.style = { backgroundColor: null };
      node.stickers = [];
      node.icons = [];
      node.attachment = null;
    }

    for (const child of node.children) traverse(child);
  }

  for (const root of tree) traverse(root);
  return tree;
}

// ---------------------------------------------------------------------------
// Attachment classification: text vs binary
// ---------------------------------------------------------------------------

/**
 * File name extensions considered textual.
 *
 * A reasonable general list of extensions whose content is readable text
 * (documents, code, serialized data). An attachment with one of these
 * extensions can be decoded as UTF-8 text without losing readability.
 *
 * @private
 * @constant {Set<string>}
 */
const TEXT_EXTENSIONS = new Set([
  'txt',
  'md',
  'markdown',
  'json',
  'csv',
  'xml',
  'html',
  'htm',
  'css',
  'js',
]);

/**
 * Extracts the lowercase extension from a file name.
 *
 * Returns the substring after the last dot (without the dot), lowercased.
 * Names without a dot, names ending in a dot ('.') or empty strings return an
 * empty string.
 *
 * @private
 * @param {string} name - File name.
 * @returns {string} Lowercase extension, or '' when there is none.
 *
 * @example
 * getFileExtension('note.txt')       // -> 'txt'
 * getFileExtension('FILE.ZIP')       // -> 'zip' (lowercase)
 * getFileExtension('no-extension')   // -> ''
 */
function getFileExtension(name) {
  const lastDot = name.lastIndexOf('.');
  if (lastDot === -1 || lastDot === name.length - 1) return '';
  return name.slice(lastDot + 1).toLowerCase();
}

/**
 * Determines whether an attachment should be treated as text or binary.
 *
 * General rules (no file-name special cases):
 * 1. TEXT when the contentType starts with 'text/' (for example 'text/plain',
 *    'text/markdown', 'text/html').
 * 2. TEXT when the name ends in a known text extension (TEXT_EXTENSIONS: .txt,
 *    .md, .markdown, .json, .csv, .xml, .html, .htm, .css, .js).
 * 3. BINARY otherwise (for example 'application/zip', 'application/pdf',
 *    'image/*', 'application/octet-stream' with a non-textual extension).
 *
 * Handling incomplete data:
 * - Empty or missing contentType -> decide by the file name extension.
 * - Name without an extension -> decide by the contentType.
 * - Empty/missing contentType AND name without an extension -> binary by
 *   default (conservative decision: avoids showing binary content as
 *   unintelligible text).
 *
 * Content type and extension comparisons are case-insensitive.
 *
 * @param {Object} attachment - Attachment metadata. It must have name and/or
 *   contentType; the remaining fields (size, content, ...) are ignored.
 * @param {string} [attachment.name] - Attachment file name.
 * @param {string} [attachment.contentType] - Attachment MIME type (may be "").
 * @returns {boolean} true when the attachment is considered text, false when
 *   binary.
 *
 * @example
 * isTextAttachment({ name: 'note.txt', contentType: 'text/plain' })      // -> true
 * isTextAttachment({ name: 'data.zip', contentType: 'application/zip' }) // -> false
 * isTextAttachment({ name: 'README.md', contentType: '' })                // -> true (by extension)
 * isTextAttachment({ name: 'no-extension', contentType: '' })             // -> false (binary default)
 * isTextAttachment({ name: 'photo.png', contentType: 'image/png' })        // -> false
 */
export function isTextAttachment(attachment) {
  if (!attachment || typeof attachment !== 'object') return false;

  const contentType = typeof attachment.contentType === 'string'
    ? attachment.contentType.trim().toLowerCase()
    : '';
  const name = typeof attachment.name === 'string' ? attachment.name : '';

  // Rule 1: contentType with a 'text/' prefix -> text.
  if (contentType.startsWith('text/')) return true;

  // Rule 2: file name extension in the textual extensions list.
  if (TEXT_EXTENSIONS.has(getFileExtension(name))) return true;

  // Rule 3: no text signals -> binary by default.
  return false;
}
