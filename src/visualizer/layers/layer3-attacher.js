/**
 * @module layer3-attacher
 * Layer 3: attach notes, external references, links, stickers and icons to
 * every tree node.
 *
 * Responsibilities:
 * 1. Create a Map indexed by node_id for notes (O(1) lookup).
 * 2. Create a Map indexed by node_id for external references (O(1) lookup).
 * 3. Create a Map indexed by from_node_id for links (O(1) lookup).
 * 4. Create a Map indexed by node_id for stickers (O(1) lookup).
 * 5. Create a Map indexed by node_id for icons (O(1) lookup).
 * 6. Ignore links with a null from_node_id or to_node_id (unresolved).
 * 7. Walk the tree recursively and attach data to every node.
 * 8. Nodes without attached data receive empty arrays (never undefined).
 * 9. Return the modified tree with complete data.
 *
 * Principle: this function MUTATES the input tree (unlike Layer 2). Every tree
 * node receives five new properties: notes[], externalRefs[], links[],
 * stickers[], icons[].
 *
 * Complexity: O(n + m), where n is the number of tree nodes and m is the total
 * of notes + refs + links + stickers + icons.
 */

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/**
 * Attaches notes, external references, links, stickers and icons to every tree
 * node.
 *
 * Receives the hierarchical tree (generated by Layer 2) and the notes, external
 * references, links, stickers and icons collections from the CMJN JSON
 * document. It builds Maps indexed by node_id for O(1) lookup and walks the
 * tree recursively, attaching the corresponding data to every node.
 *
 * Links with a null from_node_id or to_node_id are ignored (they are not
 * resolved to node UUIDs and cannot be rendered).
 *
 * The stickers and icons parameters are optional (default []) so existing calls
 * that only attach notes, refs and links keep working.
 *
 * @param {Array<Object>} tree - Hierarchical node tree (from Layer 2). Every
 *   node must have node_id and children[].
 * @param {Array<Object>} notes - Notes collection from the CMJN JSON document.
 *   Every note must have node_id, text, char_count, etc.
 * @param {Array<Object>} externalRefs - External references collection. Every
 *   ref must have node_id, url, label, ref_type, etc.
 * @param {Array<Object>} links - Links between nodes. Every link must have
 *   from_node_id, to_node_id, color, line_style, etc.
 * @param {Array<Object>} [stickers] - Stickers collection from the CMJN JSON
 *   document. Every sticker must have node_id, emoji_code, emoji_display,
 *   category, etc.
 * @param {Array<Object>} [icons] - Icons collection from the CMJN JSON
 *   document. Every icon must have node_id, url, width, height, position, etc.
 * @returns {Array<Object>} Tree with attached data. Every node now has:
 *   - notes: Array<Object> (may be empty)
 *   - externalRefs: Array<Object> (may be empty)
 *   - links: Array<Object> (may be empty)
 *   - stickers: Array<Object> (may be empty)
 *   - icons: Array<Object> (may be empty)
 *
 * @example
 * const tree = [{ node_id: 'a', children: [{ node_id: 'b', children: [] }] }];
 * const notes = [{ node_id: 'a', text: 'Root note', char_count: 10 }];
 * const refs = [{ node_id: 'b', url: 'https://example.com', label: 'Example' }];
 * const links = [{ from_node_id: 'a', to_node_id: 'b', color: '#FF0000' }];
 * const stickers = [{ node_id: 'a', emoji_code: 'emoji:1F5FA', emoji_display: '🗺️' }];
 * const icons = [{ node_id: 'a', url: 'data:image/png;base64,...', width: 32, height: 32 }];
 * const result = attachData(tree, notes, refs, links, stickers, icons);
 * // result[0].notes = [{ node_id: 'a', text: 'Root note', char_count: 10 }]
 * // result[0].children[0].externalRefs = [{ node_id: 'b', url: '...', label: '...' }]
 * // result[0].links = [{ from_node_id: 'a', to_node_id: 'b', color: '#FF0000' }]
 * // result[0].stickers = [{ node_id: 'a', emoji_code: 'emoji:1F5FA', ... }]
 * // result[0].icons = [{ node_id: 'a', url: 'data:image/png;base64,...', ... }]
 */
export function attachData(tree, notes = [], externalRefs = [], links = [], stickers = [], icons = []) {
  // Maps for O(1) lookup by node_id.

  /** @type {Map<string, Array<Object>>} */
  const notesMap = new Map();
  for (const note of (notes || [])) {
    if (!notesMap.has(note.node_id)) notesMap.set(note.node_id, []);
    notesMap.get(note.node_id).push(note);
  }

  /** @type {Map<string, Array<Object>>} */
  const refsMap = new Map();
  for (const ref of (externalRefs || [])) {
    if (!refsMap.has(ref.node_id)) refsMap.set(ref.node_id, []);
    refsMap.get(ref.node_id).push(ref);
  }

  /** @type {Map<string, Array<Object>>} */
  const linksMap = new Map();
  for (const link of (links || [])) {
    // Process only resolved links (from_node_id and to_node_id not null).
    if (link.from_node_id && link.to_node_id) {
      if (!linksMap.has(link.from_node_id)) linksMap.set(link.from_node_id, []);
      linksMap.get(link.from_node_id).push(link);
    }
  }

  /** @type {Map<string, Array<Object>>} */
  const stickersMap = new Map();
  for (const sticker of (stickers || [])) {
    if (!stickersMap.has(sticker.node_id)) stickersMap.set(sticker.node_id, []);
    stickersMap.get(sticker.node_id).push(sticker);
  }

  /** @type {Map<string, Array<Object>>} */
  const iconsMap = new Map();
  for (const icon of (icons || [])) {
    if (!iconsMap.has(icon.node_id)) iconsMap.set(icon.node_id, []);
    iconsMap.get(icon.node_id).push(icon);
  }

  // Walk the tree recursively and attach data to every node.
  function traverse(node) {
    node.notes = notesMap.get(node.node_id) || [];
    node.externalRefs = refsMap.get(node.node_id) || [];
    node.links = linksMap.get(node.node_id) || [];
    node.stickers = stickersMap.get(node.node_id) || [];
    node.icons = iconsMap.get(node.node_id) || [];
    for (const child of node.children) traverse(child);
  }

  for (const root of tree) traverse(root);
  return tree;
}
