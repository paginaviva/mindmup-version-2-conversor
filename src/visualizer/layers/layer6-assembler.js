/**
 * Sanitizes JSON before inserting it into a <script> tag.
 *
 * Prevents XSS when JSON is inserted inside a <script> element. JSON.stringify()
 * does NOT escape the </script> sequence, which would let an attacker close the
 * script block early and inject malicious code.
 *
 * This function applies three defensive replacements:
 * - </ -> <\/ (breaks the </script> sequence that closes the block).
 * - <!-- -> <\!-- (breaks HTML comments that could hide code).
 * - ]]> -> ]]\\> (breaks CDATA sections that could be interpreted as markup).
 *
 * The replacements are safe because the JSON parser inside <script> ignores the
 * escape backslashes in strings, while the HTML parser does not interpret them
 * as part of the dangerous sequences.
 *
 * @private
 * @param {Object} obj - Object to serialize for insertion into <script>.
 * @returns {string} Stringified, sanitized JSON, safe for <script>.
 *
 * @example
 * safeJsonForScript({ title: '</script><script>alert(1)</script>' })
 * // -> '{"title":"<\\/script><script>alert(1)<\\/script>"}'
 * // The browser does not execute the second <script> because </ is escaped as <\/
 */
function safeJsonForScript(obj) {
  return JSON.stringify(obj)
    .replace(/<\//g, '<\\/')      // </ -> <\/ (breaks </script>)
    .replace(/<!--/g, '<\\!--')   // <!-- -> <\!-- (breaks HTML comments)
    .replace(/\]\]>/g, ']]\\>');  // ]]> -> ]]\\> (breaks CDATA)
}

/**
 * Accepted CSP nonce pattern (standard or URL-safe base64, 8-64 chars).
 *
 * Restricts the value inserted into the nonce="" attribute of <script>: it
 * discards quotes, angle brackets and any other character that could break the
 * attribute. The Worker generates the nonce with crypto.getRandomValues(), but
 * this layer does not trust its input (defense in depth).
 *
 * @private
 * @type {RegExp}
 */
const NONCE_PATTERN = /^[A-Za-z0-9+/=_-]{8,64}$/;

/**
 * Normalizes and validates a CSP nonce.
 *
 * @private
 * @param {*} nonce - Value to validate (a string is expected).
 * @returns {string} Valid nonce, or an empty string when it is missing or does
 *   not match the pattern.
 */
function normalizeNonce(nonce) {
  return (typeof nonce === 'string' && NONCE_PATTERN.test(nonce)) ? nonce : '';
}

