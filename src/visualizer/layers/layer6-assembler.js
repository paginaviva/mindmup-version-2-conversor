// --- Defensa en profundidad: validar atributos SVG de los links ---
// El color debe ser un hexadecimal #RRGGBB (respaldo #808000) y el ancho un
// número finito positivo (respaldo 2). Evita valores inyectados o no
// numéricos en el SVG generado desde datos no confiables del mapa.
function safeLinkColor(color) {
  return (typeof color === 'string' && /^#[0-9A-Fa-f]{6}$/.test(color)) ? color : '#808000';
}

function safeLinkWidth(width) {
  const value = Number(width);
  return Number.isFinite(value) && value > 0 ? value : 2;
}

// --- SVG overlay para links entre nodos ---
function updateLinksOverlay() {
  const svg = document.getElementById('links-overlay');
  const links = (typeof MMUP_DATA !== 'undefined' && MMUP_DATA.links) ? MMUP_DATA.links : [];

  // Limpiar SVG
  svg.innerHTML = '';

  // Dibujar cada link resuelto
  links.forEach(link => {
    if (!link.from_node_id || !link.to_node_id) {
      return; // Skip links no resueltos
    }

    const fromElement = document.querySelector('.node[data-id="' + CSS.escape(link.from_node_id) + '"] .node-header');
    const toElement = document.querySelector('.node[data-id="' + CSS.escape(link.to_node_id) + '"] .node-header');

    if (!fromElement || !toElement) {
      return; // Skip si nodos no están en DOM (colapsados)
    }

    const fromRect = fromElement.getBoundingClientRect();
    const toRect = toElement.getBoundingClientRect();
    const wrapperRect = document.getElementById('tree-wrapper').getBoundingClientRect();

    const x1 = fromRect.left + fromRect.width / 2 - wrapperRect.left;
    const y1 = fromRect.top + fromRect.height / 2 - wrapperRect.top;
    const x2 = toRect.left + toRect.width / 2 - wrapperRect.left;
    const y2 = toRect.top + toRect.height / 2 - wrapperRect.top;

    // Validar color y ancho antes de usarlos en atributos SVG
    const strokeColor = safeLinkColor(link.color);
    const strokeWidth = safeLinkWidth(link.width);

    // Crear path SVG
    const path = document.createElementNS('http://www.w3.org/2000/svg', 'path');
    path.setAttribute('d', 'M ' + x1 + ' ' + y1 + ' L ' + x2 + ' ' + y2);
    path.setAttribute('stroke', strokeColor);
    path.setAttribute('stroke-width', strokeWidth);
    path.setAttribute('fill', 'none');

    // Estilo de línea
    if (link.line_style === 'dashed') {
      path.setAttribute('stroke-dasharray', '5,5');
    } else if (link.line_style === 'dotted') {
      path.setAttribute('stroke-dasharray', '2,2');
    }

    svg.appendChild(path);

    // Flechas (markers) en los extremos
    if (link.arrow === 'to' || link.arrow === 'both') {
      drawArrow(svg, x2, y2, strokeColor, Math.atan2(y2 - y1, x2 - x1));
    }
    if (link.arrow === 'from' || link.arrow === 'both') {
      drawArrow(svg, x1, y1, strokeColor, Math.atan2(y1 - y2, x1 - x2));
    }
  });
}

/**
 * Dibuja una flecha SVG en la posición (x, y) con el ángulo dado.
 */
function drawArrow(svg, x, y, color, angle) {
  const size = 10;
  const path = document.createElementNS('http://www.w3.org/2000/svg', 'path');

  const x1 = x - size * Math.cos(angle - Math.PI / 6);
  const y1 = y - size * Math.sin(angle - Math.PI / 6);
  const x2 = x - size * Math.cos(angle + Math.PI / 6);
  const y2 = y - size * Math.sin(angle + Math.PI / 6);

  path.setAttribute('d', 'M ' + x + ' ' + y + ' L ' + x1 + ' ' + y1 + ' L ' + x2 + ' ' + y2 + ' Z');
  // Doble validación del color también en el extremo de la flecha
  path.setAttribute('fill', safeLinkColor(color));

  svg.appendChild(path);
}

