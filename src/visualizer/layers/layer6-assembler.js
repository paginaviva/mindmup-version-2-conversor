/**
 * Assembles the complete visualizer HTML document.
 *
 * Receives the tree HTML (from Layer 5), the map metadata and the links,
 * stickers and icons collections. It produces a self-contained HTML document
 * with inline CSS, inline JS, embedded JSON (MMUP_DATA) and an SVG overlay for
 * links between nodes. Stickers and icons are transmitted to the browser inside
 * MMUP_DATA.
 *
 * The resulting HTML is a complete document ready to be served to the browser,
 * with no external dependencies (all CSS and JS are inline).
 *
 * @param {string} treeHTML - Tree HTML generated by Layer 5 (renderTree). It
 *   contains the role='tree' container with every rendered node.
 * @param {Object} metadata - Map metadata from the MMUP JSON document. It must
 *   have: title, source_file, converted_at and node_count.
 * @param {Array<Object>} links - Links between nodes. Every link must have:
 *   link_id, from_node_id, to_node_id, color, line_style, arrow, width and
 *   resolution.
 * @param {Array<Object>} [stickers] - Stickers collection from the MMUP JSON
 *   document. Every sticker must have: sticker_id, node_id, emoji_code,
 *   emoji_display and category.
 * @param {Array<Object>} [icons] - Icons collection from the MMUP JSON
 *   document. Every icon must have: icon_id, node_id, url, width, height and
 *   position.
 * @param {Array<Object>} [attachments] - Map attachments for the internal modal
 *   and the download links. Every attachment must have: node_id, name,
 *   contentType and content (data URI "data:{mime};base64,..."). They are
 *   transmitted in MMUP_DATA so the modal can decode text content and the
 *   download links (.attachment-download) can obtain their href without
 *   exposing all raw_attributes.
 * @param {Object} [options={}] - Assembly options.
 * @param {string} [options.nonce] - CSP nonce for the <script> tags. When it is
 *   missing or does not have a valid format (base64/url-safe, 8-64 characters),
 *   it is ignored and the HTML is generated without a nonce attribute
 *   (backward compatible).
 * @returns {string} Complete HTML document ready to be served
 *   (Content-Type: text/html).
 *
 * @example
 * const treeHTML = '<div id="tree-container" role="tree">...</div>';
 * const metadata = { title: 'Mi mapa', node_count: 100, source_file: 'mapa.mup', converted_at: '2026-07-23T10:00:00Z' };
 * const links = [{ from_node_id: 'a', to_node_id: 'b', color: '#FF0000' }];
 * const stickers = [{ sticker_id: 's1', node_id: 'a', emoji_code: 'emoji:1F5FA', emoji_display: '🗺️', category: 'travel' }];
 * const icons = [{ icon_id: 'i1', node_id: 'a', url: 'data:image/png;base64,...', width: 32, height: 32, position: 'left' }];
 * const attachments = [{ node_id: 'a', name: 'nota.txt', contentType: 'text/plain', content: 'data:text/plain;base64,...' }];
 * const html = assembleHTML(treeHTML, metadata, links, stickers, icons, attachments);
 * // html is a complete document with <!DOCTYPE html>, CSS, JS and SVG overlay.
 *
 * @example
 * // With a CSP nonce (Worker + Durable Object):
 * const html = assembleHTML(treeHTML, metadata, links, stickers, icons, attachments, { nonce: 'abc123==' });
 * // -> '<script nonce="abc123==">const MMUP_DATA = ...'
 */
export function assembleHTML(treeHTML, metadata, links, stickers = [], icons = [], attachments = [], options = {}) {
  const title = escapeHtml(metadata.title || 'Sin título');
  const mmupDataJSON = safeJsonForScript({ metadata, links, stickers, icons, attachments });
  const nonce = normalizeNonce(options && options.nonce);
  const scriptNonceAttr = nonce ? ` nonce="${nonce}"` : '';

  return `<!DOCTYPE html>
<!-- Copyright (c) 2026 Paginaviva. MIT License. -->
<html lang="es">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Visor mmup — ${title}</title>
  <style>${getCSS()}</style>
</head>
<body>
  <div id="app">
    <header>
      <h1>${title}</h1>
      <div class="meta">
        <span>${escapeHtml(String(metadata.node_count || 0))} nodos</span>
        <span>${escapeHtml(metadata.source_file || '')}</span>
        <span>${formatDate(metadata.converted_at)}</span>
      </div>
      <div class="controls">
        <button id="expand-all" aria-label="Expandir todo">Expandir todo</button>
        <button id="collapse-all" aria-label="Colapsar todo">Colapsar todo</button>
        <label class="theme-switch" title="Aplicar el color de fondo del lienzo definido por el tema del mapa">
          <input type="checkbox" id="theme-toggle"> Aplicar tema del mapa
        </label>
        <span id="node-counter">0 / ${escapeHtml(String(metadata.node_count || 0))} nodos visibles</span>
      </div>
    </header>
    <details id="index-container">
      <summary>Índice de nodos</summary>
      <div id="index-list"></div>
    </details>
    <div id="breadcrumb" class="breadcrumb" style="display: none;"></div>
    <div id="tree-wrapper" style="position: relative;">
      ${treeHTML}
      <svg id="links-overlay" style="position: absolute; top: 0; left: 0; width: 100%; height: 100%; pointer-events: none;"></svg>
    </div>
  </div>
  <div id="attachment-modal" class="modal-overlay" hidden>
    <div class="modal" role="dialog" aria-modal="true" aria-labelledby="attachment-modal-title">
      <div class="modal-header">
        <h2 id="attachment-modal-title">Adjunto</h2>
        <button type="button" class="modal-close" aria-label="Cerrar">×</button>
      </div>
      <div class="modal-body" id="attachment-modal-body"></div>
    </div>
  </div>
  <script${scriptNonceAttr}>const MMUP_DATA = ${mmupDataJSON};</script>
  <script${scriptNonceAttr}>${getJavaScript()}</script>
</body>
</html>`;
}

