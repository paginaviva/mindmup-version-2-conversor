/**
 * Formats an ISO 8601 date into a human-readable Spanish format.
 *
 * Converts an ISO date string (for example "2026-07-23T10:00:00Z") into a
 * readable format: "23 de julio de 2026, 10:00". Invalid or null dates return
 * "Fecha desconocida".
 *
 * @param {string|null|undefined} iso - Date in ISO 8601 format.
 * @returns {string} Formatted Spanish date or "Fecha desconocida" when invalid.
 *
 * @example
 * formatDate('2026-07-23T10:00:00Z')  // -> '23 de julio de 2026, 10:00'
 * formatDate(null)                     // -> 'Fecha desconocida'
 * formatDate('invalid')                // -> 'Fecha desconocida'
 */
export function formatDate(iso) {
  if (!iso) return 'Fecha desconocida';

  try {
    const date = new Date(iso);
    // Verify that the date is valid.
    if (isNaN(date.getTime())) return 'Fecha desconocida';

    return date.toLocaleDateString('es-ES', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit'
    });
  } catch {
    return 'Fecha desconocida';
  }
}

/**
 * Escapes the special characters of a text for safe HTML insertion.
 *
 * Replaces the five dangerous HTML characters with their entities:
 * - & -> &amp;
 * - < -> &lt;
 * - > -> &gt;
 * - " -> &quot;
 * - ' -> &#039;
 *
 * This function is critical to prevent XSS. It is applied to every dynamic
 * value inserted into the assembled HTML (title and source_file).
 *
 * @param {string} text - Text to escape. Non-string values are converted.
 * @returns {string} Escaped text, safe to insert into HTML.
 *
 * @example
 * escapeHtml('<script>alert("xss")</script>')
 * // -> '&lt;script&gt;alert(&quot;xss&quot;)&lt;/script&gt;'
 */
export function escapeHtml(text) {
  return String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}
