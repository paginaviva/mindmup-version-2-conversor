// --- Decodificar contenido base64 de una data URI a texto UTF-8 ---
// El contenido llega como "data:{mime};base64,{payload}". Se descarta el
// prefijo y se decodifica el payload. El BOM UTF-8 (si existe) se elimina
// automáticamente por TextDecoder.
function decodeAttachmentContent(content) {
  if (typeof content !== 'string') return null;
  const commaIndex = content.indexOf(',');
  const base64 = commaIndex === -1 ? content : content.slice(commaIndex + 1);
  try {
    const binary = atob(base64);
    const bytes = Uint8Array.from(binary, c => c.charCodeAt(0));
    return new TextDecoder('utf-8').decode(bytes);
  } catch (e) {
    return null;
  }
}

