// --- Abrir el modal con el contenido decodificado del adjunto ---
function openAttachmentModal(nodeId) {
  const modal = document.getElementById('attachment-modal');
  const body = document.getElementById('attachment-modal-body');
  const title = document.getElementById('attachment-modal-title');
  if (!modal || !body) return;

  const attachments = (typeof MMUP_DATA !== 'undefined' && MMUP_DATA.attachments) ? MMUP_DATA.attachments : [];
  const attachment = attachments.find(a => a.node_id === nodeId);

  if (!attachment || !attachment.content) {
    title.textContent = 'Adjunto no disponible';
    body.textContent = 'No se encontró el contenido del adjunto para este nodo.';
    modal.hidden = false;
    return;
  }

  const name = attachment.name || 'Adjunto';
  const contentType = attachment.contentType || '';
  title.textContent = 'Adjunto: ' + name;

  // Defensa general: si el adjunto es binario (p.ej. application/zip), no
  // tiene sentido decodificarlo como texto UTF-8 (saldría ininteligible).
  // Normalmente los binarios se renderizan como .attachment-download y nunca
  // llegan aquí; esta rama cubre datos inconsistentes o árboles no
  // clasificados por la Capa 4.
  if (!isTextAttachment(attachment)) {
    body.textContent = 'El adjunto "' + name + '" es un archivo binario' +
      (contentType ? ' (tipo ' + contentType + ')' : '') +
      ' y no se puede visualizar como texto. Usa el enlace de descarga del nodo para descargarlo.';
    modal.hidden = false;
    return;
  }

  const decoded = decodeAttachmentContent(attachment.content);

  if (decoded === null) {
    body.textContent = 'No se pudo decodificar el contenido del adjunto (' + name + ').';
  } else {
    // Texto plano con salto de línea conservado (pre-wrap); sin renderizar
    // markdown: mostrar el texto tal cual es suficiente y seguro.
    body.textContent = decoded;
  }

  modal.hidden = false;
}

// --- Clasificación general texto/binario (espejo de la Capa 4) ---
// El documento HTML es autocontenido (CSS y JS inline, sin imports), por lo
// que esta función replica las reglas de isTextAttachment() en
// src/layers/layer4-styler.js: contentType con prefijo 'text/' o extensión
// textual → texto; en caso contrario → binario. contentType vacío/ausente se
// decide por la extensión; sin extensión → binario por defecto.
function isTextAttachment(attachment) {
  if (!attachment || typeof attachment !== 'object') return false;
  const contentType = (typeof attachment.contentType === 'string' ? attachment.contentType.trim().toLowerCase() : '');
  if (contentType.indexOf('text/') === 0) return true;
  const name = (typeof attachment.name === 'string' ? attachment.name : '');
  const lastDot = name.lastIndexOf('.');
  const extension = (lastDot === -1 || lastDot === name.length - 1) ? '' : name.slice(lastDot + 1).toLowerCase();
  return ['txt', 'md', 'markdown', 'json', 'csv', 'xml', 'html', 'htm', 'css', 'js'].indexOf(extension) !== -1;
}

