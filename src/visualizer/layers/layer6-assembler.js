/**
 * @module layer6-assembler
 * Layer 6: assemble the complete HTML document with CSS, JS and the SVG
 * overlay.
 *
 * Responsibilities:
 * 1. Generate a complete HTML document (<!DOCTYPE html>) with lang='es' and
 *    UTF-8 charset.
 * 2. Title from metadata.title, escaped (anti-XSS).
 * 3. Inline CSS in <style> with every visualizer style.
 * 4. Header with h1 (title), meta (nodes, file, date) and controls.
 * 5. "Expandir todo" / "Colapsar todo" buttons with aria-label.
 * 6. Visible-node counter (id='node-counter').
 * 7. Collapsible index with <details id='index-container'>.
 * 8. Breadcrumb (id='breadcrumb') initially hidden.
 * 9. Tree wrapper with position: relative for the SVG overlay.
 * 10. SVG overlay (id='links-overlay') with pointer-events: none.
 * 11. JSON embedded in <script> as const MMUP_DATA (metadata, links, stickers,
 *     icons and attachments).
 * 12. Inline JavaScript in <script> with all interactive logic.
 * 12b. Optional CSP nonce support on both <script> tags (options.nonce);
 *      without a nonce the HTML is generated exactly as before (backward
 *      compatible).
 * 13. JS includes: toggleNode, expandAll, collapseAll and updateNodeCounter.
 * 14. JS includes: showBreadcrumb, buildIndex, updateLinksOverlay and
 *     drawArrow.
 * 15. JS includes keyboard navigation (Enter/Space on toggles).
 * 16. JS includes scroll/resize listeners for the SVG overlay.
 * 17. CSS for node icons (.node-icon): maximum dimensions, margin and vertical
 *     alignment.
 * 18. Modal window for text attachments: one 📎 link per node, base64 content
 *     decoding and safe text rendering.
 * 19. Binary attachments: direct download links (.attachment-download) with
 *     href = content data URI and download = file name, assigned from
 *     MMUP_DATA.attachments; the modal shows a notice when it receives a
 *     binary attachment.
 * 20. Theme switch: applies or removes the canvas background color from
 *     metadata.themeOverrides.canvas.backgroundColor.
 *
 * Principle: this function is PURE; it does not mutate its inputs and produces
 * an HTML string. The resulting HTML is self-contained (inline CSS + JS, no
 * external dependencies).
 */

