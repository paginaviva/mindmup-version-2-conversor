/**
 * @module layer2-tree-builder
 * Layer 2: build the hierarchical tree from flat nodes.
 *
 * Responsibilities:
 * 1. Index all nodes by node_id in a Map (O(1) lookup).
 * 2. Copy each node with spread to preserve input immutability.
 * 3. Add an empty `children: []` array to every copied node.
 * 4. Nest children under their parents using parent_id.
 * 5. Send nodes with a null or unknown parent_id to the roots array.
 * 6. Sort children[] by ascending sibling_order.
 * 7. Return the roots array (there may be multiple roots).
 *
 * Immutability principle: this function does NOT mutate the input array or the
 * original objects. Every node is copied with the spread operator.
 *
 * Complexity: O(n log n) due to sorting, O(n) for indexing and nesting.
 */

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/**
 * Transforms a flat node collection into a nested hierarchy.
 *
 * Receives the `nodes[]` array from the CMJN JSON document (generated by the
 * converter) and builds a tree where every node contains a `children[]` array
 * with its nested children. The function is pure: it does not mutate the input.
 *
 * Three-phase algorithm:
 * - Phase 1: Index nodes by copying them with `children: []` (Map by node_id).
 * - Phase 2: Nest children under parents using parent_id; nodes without a valid
 *   parent go to the roots array.
 * - Phase 3: Sort children[] by ascending sibling_order.
 *
 * Handled edge cases:
 * - Empty array or null/undefined -> returns `[]`.
 * - Nodes with an unknown parent_id (parent is not in the array) -> roots.
 * - Multiple roots (several nodes with a null parent_id) -> an array with all
 *   of them.
 *
 * @param {Array<Object>} nodes - Flat node collection from the CMJN JSON
 *   document. Every node must have node_id, parent_id, sibling_order and any
 *   additional fields.
 * @returns {Array<Object>} Hierarchical tree with nested children[]. Every
 *   result node keeps its original properties plus `children: Array<Object>`.
 *
 * @example
 * const nodes = [
 *   { node_id: 'a', parent_id: null, sibling_order: 0, title: 'Root' },
 *   { node_id: 'b', parent_id: 'a', sibling_order: 0, title: 'Child 1' },
 *   { node_id: 'c', parent_id: 'a', sibling_order: 1, title: 'Child 2' },
 * ];
 * const tree = buildTree(nodes);
 * // tree = [{
 * //   node_id: 'a', parent_id: null, title: 'Root',
 * //   children: [
 * //     { node_id: 'b', parent_id: 'a', title: 'Child 1', children: [] },
 * //     { node_id: 'c', parent_id: 'a', title: 'Child 2', children: [] }
 * //   ]
 * // }]
 */
export function buildTree(nodes) {
  // Edge case: empty or invalid input.
  if (!nodes || nodes.length === 0) return [];

  /** @type {Map<string, Object>} */
  const nodeIndex = new Map();

  /** @type {Array<Object>} */
  const roots = [];

  // Phase 1: index nodes (immutability: spread copy + empty children).
  for (const node of nodes) {
    nodeIndex.set(node.node_id, { ...node, children: [] });
  }

  // Phase 2: nest children under parents.
  // A null, falsy or unknown parent_id sends the node to roots.
  for (const node of nodeIndex.values()) {
    if (node.parent_id && nodeIndex.has(node.parent_id)) {
      nodeIndex.get(node.parent_id).children.push(node);
    } else {
      roots.push(node);
    }
  }

  // Phase 3: sort children by ascending sibling_order.
  for (const node of nodeIndex.values()) {
    node.children.sort((a, b) => a.sibling_order - b.sibling_order);
  }

  return roots;
}
