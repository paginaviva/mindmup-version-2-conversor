/**
 * Map list endpoint path.
 *
 * @type {string}
 */
const LIST_PATH = '/visor/api/lista';

/**
 * Map visualization endpoint prefix.
 *
 * @type {string}
 */
const OUTPUT_PATH_PREFIX = '/visor/mmup-output/';

/**
 * Maximum number of objects returned by one R2 list() call.
 *
 * This is the R2 API maximum (a protocol limit, not an operational value).
 *
 * @type {number}
 */
const R2_LIST_PAGE_SIZE = 1000;

