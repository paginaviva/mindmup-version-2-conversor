/**
 * Extracts the identifier from an R2 object key.
 *
 * Removes the configured storage prefix and JSON suffix. Returns null when the
 * key does not match the configured shape, so non-JSON objects are ignored
 * instead of producing broken identifiers.
 *
 * @param {string} key - R2 object key.
 * @param {string} outputPrefix - Injected storage prefix.
 * @param {string} jsonSuffix - Injected JSON suffix.
 * @returns {string|null} Identifier, or null when the key does not match.
 */
function extractIdentifier(key, outputPrefix, jsonSuffix) {
  if (typeof key !== 'string' || !key.startsWith(outputPrefix)) return null;
  const withoutPrefix = key.slice(outputPrefix.length);
  if (!withoutPrefix.endsWith(jsonSuffix)) return null;
  return withoutPrefix.slice(0, withoutPrefix.length - jsonSuffix.length);
}

/**
 * Handles GET /visor/api/lista - lists the JSON documents in R2 with metadata.
 *
 * Runs R2.list() with the injected storage prefix, reads each JSON document to
 * extract metadata (title, converted_at, node_count and source_file), sorts by
 * converted_at descending and returns JSON with the list.
 *
 * If one JSON document cannot be read, the error is logged and processing
 * continues with the next item (the whole list is not aborted).
 *
 * @param {Object} env - Worker bindings (must include env.MMUP_BUCKET).
 * @param {Object} config - Validated configuration.
 * @returns {Promise<Response>} JSON response with { success, count, items }.
 *   Cache-Control comes from config.listCacheSeconds.
 */
async function handleList(env, config) {
  const startTime = Date.now();
  console.log(JSON.stringify({ level: 'info', action: 'list_start' }));

  const bucket = env.MMUP_BUCKET;
  if (!bucket || typeof bucket.list !== 'function' || typeof bucket.get !== 'function') {
    throw configError(
      'MISSING_BUCKET_BINDING',
      'Falta el binding "MMUP_BUCKET" en el entorno',
    );
  }

  const items = [];
  let cursor = undefined;
  let truncated = true;

  // Full R2.list() pagination - avoids losing objects beyond the page size.
  while (truncated) {
    const listOptions = { prefix: config.outputPrefix, limit: R2_LIST_PAGE_SIZE };
    if (cursor) listOptions.cursor = cursor;

    const result = await bucket.list(listOptions);
    const objects = Array.isArray(result.objects) ? result.objects : [];

    for (const entry of objects) {
      const uuid = extractIdentifier(entry.key, config.outputPrefix, config.jsonSuffix);
      if (uuid === null) {
        console.warn(JSON.stringify({
          level: 'warning',
          action: 'list_skip_object',
          key: entry.key,
          reason: 'KEY_DOES_NOT_MATCH_CONFIGURED_SHAPE',
        }));
        continue;
      }

      try {
        const object = await bucket.get(entry.key);
        const data = await object.json();

        items.push({
          uuid,
          title: data.metadata?.title || 'Sin título',
          source_file: data.metadata?.source_file || '',
          converted_at: data.metadata?.converted_at || '',
          node_count: data.metadata?.node_count || 0
        });
      } catch (error) {
        console.error(JSON.stringify({ level: 'error', action: 'list_item_error', uuid, error: error.message }));
        // Continue with the next item.
      }
    }

    truncated = result.truncated;
    cursor = result.cursor;
  }

  // Sort by date descending (newest first).
  items.sort((a, b) => new Date(b.converted_at) - new Date(a.converted_at));

  const duration = Date.now() - startTime;
  console.log(JSON.stringify({ level: 'info', action: 'list_complete', count: items.length, duration_ms: duration }));

  return Response.json(
    { success: true, count: items.length, items },
    { headers: { 'Cache-Control': `public, max-age=${config.listCacheSeconds}` } }
  );
}

/**
 * Handles GET /visor/mmup-output/{uuid} - generates the HTML for one identifier.
 *
 * Gets the Durable Object stub from the injected binding name, calls the
 * Durable Object through the internal /convert/{uuid} route and returns the
 * generated HTML.
 *
 * The CSP nonce and the R2 key template travel to the Durable Object in
 * internal headers so the Durable Object does not hardcode either value.
 *
 * Durable Object errors:
 * - 404 -> 404 error HTML (identifier not found).
 * - 400 -> 400 error HTML (invalid JSON or structure).
 * - Anything else -> 500 error HTML with a generic message (details are only
 *   logged).
 *
 * @param {string} uuid - Unique identifier of the JSON in R2.
 * @param {Object} env - Worker bindings.
 * @param {string} nonce - Request CSP nonce.
 * @param {Object} config - Validated configuration.
 * @returns {Promise<Response>} Response with HTML (200) or error HTML
 *   (404/400/500). Cache-Control is private, no-store for successful HTML
 *   (it contains a per-request CSP nonce).
 */
async function handleVisualize(uuid, env, nonce, config, request) {
  const startTime = Date.now();
  console.log(JSON.stringify({ level: 'info', action: 'visualize_start', uuid }));

  const durableObject = env[config.durableObjectBinding];
  if (
    !durableObject ||
    typeof durableObject.idFromName !== 'function' ||
    typeof durableObject.get !== 'function'
  ) {
    throw configError(
      'MISSING_DO_BINDING',
      `Falta el binding "${config.durableObjectBinding}" en el entorno`,
    );
  }

  // Get the Durable Object stub.
  const id = durableObject.idFromName(uuid);
  const stub = durableObject.get(id);

  // Build the R2 key template from the injected prefix and suffix; the
  // placeholder is filled by Layer 1.
  const keyTemplate = new URL(request.url).searchParams.get('keyTemplate')
    || request.headers.get('X-MMUP-Key-Template')
    || `${config.outputPrefix}{uuid}${config.jsonSuffix}`;

  // Call the Durable Object to generate HTML, passing the nonce and key
  // template in internal headers.
  const response = await stub.fetch(new Request(
    `http://do/convert/${uuid}?keyTemplate=${encodeURIComponent(keyTemplate)}`,
    {
      headers: {
        [NONCE_HEADER]: nonce,
        [KEY_TEMPLATE_HEADER]: keyTemplate,
      }
    }
  ));

  if (!response.ok) {
    const status = response.status;
    const errorText = await response.text();

    console.error(JSON.stringify({
      level: 'error',
      action: 'visualize_do_error',
      uuid,
      status,
      error: errorText
    }));

    if (status === 404) {
      return new Response(render404HTML(uuid), {
        status: 404,
        headers: { 'Content-Type': 'text/html; charset=utf-8' }
      });
    }
    if (status === 400) {
      // Do not forward the internal Durable Object body to the user; map it to
      // a public message and keep the original code only in the logs.
      const publicMessages = {
        INVALID_JSON: 'El mapa no se pudo procesar: el archivo no es un JSON válido.',
        INVALID_STRUCTURE: 'El mapa no se pudo procesar: la estructura no es válida.'
      };
      const publicMessage = publicMessages[errorText.trim()] || 'La solicitud no es válida.';
      return new Response(render400HTML(publicMessage), {
        status: 400,
        headers: { 'Content-Type': 'text/html; charset=utf-8' }
      });
    }

    // The user receives a generic message: errorText (internal Durable Object
    // detail) was already logged above.
    return new Response(render500HTML(), {
      status: 500,
      headers: { 'Content-Type': 'text/html; charset=utf-8' }
    });
  }

  const html = await response.text();
  const duration = Date.now() - startTime;
  console.log(JSON.stringify({ level: 'info', action: 'visualize_complete', uuid, duration_ms: duration }));

  return new Response(html, {
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
      'Cache-Control': 'private, no-store'
    }
  });
}
