// CORS headers
// ---------------------------------------------------------------------------

/**
 * Adds CORS headers to a response.
 *
 * The allowed origins and the preflight cache duration come from the injected
 * configuration. When the request origin is listed, it is echoed back;
 * otherwise the wildcard is used, preserving the current behavior.
 *
 * When the configuration is not available (for routes that do not need it,
 * such as 404 or invalid-identifier responses), only the protocol-level CORS
 * headers are added and no origin is authorized.
 *
 * @param {Response} response - Original response.
 * @param {Request} request - Original request (used to read the Origin header).
 * @param {Object|null} config - Validated configuration, or null when the
 *   route does not require it.
 * @returns {Response} New response with the CORS headers.
 */
function addCorsHeaders(response, request, config) {
  const headers = new Headers(response.headers);
  headers.set('Access-Control-Allow-Methods', 'GET, OPTIONS');
  headers.set('Access-Control-Allow-Headers', 'Content-Type');

  if (config) {
    const origin = request.headers.get('Origin') || '*';
    const allowedOrigin = config.allowedOrigins.includes(origin) ? origin : '*';
    headers.set('Access-Control-Allow-Origin', allowedOrigin);
    headers.set('Access-Control-Max-Age', String(config.corsMaxAgeSeconds));
  }

  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

// ---------------------------------------------------------------------------
// Security headers and CSP nonce
// ---------------------------------------------------------------------------

/**
 * Security headers common to every Worker response.
 *
 * @type {Object<string, string>}
 */
const SECURITY_HEADERS = {
  'X-Content-Type-Options': 'nosniff',
  'Referrer-Policy': 'no-referrer',
  'X-Frame-Options': 'SAMEORIGIN',
};

/**
 * Generates a cryptographically secure CSP nonce (16 random bytes in base64).
 *
 * Uses crypto.getRandomValues (the platform CSPRNG), never Math.random. Every
 * request receives a different nonce, so a nonce leaked in a cached HTML
 * document cannot authorize scripts in another response.
 *
 * @returns {string} Base64 nonce (24 characters including padding).
 */
function generateNonce() {
  const bytes = new Uint8Array(16);
  crypto.getRandomValues(bytes);
  return btoa(String.fromCharCode(...bytes));
}

/**
 * Builds the Content-Security-Policy of the viewer HTML with a nonce.
 *
 * Restrictive policy: no external resources, no forms, only same-origin frames
 * and only the inline scripts marked with the request nonce. `img-src` allows data: (inline
 * icons) and https: (remote map icons); `style-src 'unsafe-inline'` covers the
 * viewer inline CSS.
 *
 * @param {string} nonce - Request nonce.
 * @returns {string} Content-Security-Policy header value.
 */
function buildCsp(nonce) {
  return `default-src 'none'; script-src 'nonce-${nonce}'; style-src 'unsafe-inline'; img-src data: https:; base-uri 'none'; form-action 'none'; frame-ancestors 'self'; object-src 'none'`;
}

/**
 * Adds the common security headers and the CSP to a response.
 *
 * @param {Response} response - Original response.
 * @param {string} nonce - Request CSP nonce.
 * @returns {Response} New response with the security headers.
 */
function addSecurityHeaders(response, nonce) {
  const headers = new Headers(response.headers);
  for (const [name, value] of Object.entries(SECURITY_HEADERS)) {
    headers.set(name, value);
  }
  headers.set('Content-Security-Policy', buildCsp(nonce));

  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

