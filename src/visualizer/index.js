// Worker entry point
// ---------------------------------------------------------------------------

export default {
  /**
   * Handles every incoming HTTP request to the Worker.
   *
   * Supported routes:
   * - GET /visor/api/lista -> lists the JSON documents in R2 with metadata.
   * - GET /visor/mmup-output/{uuid} -> generates the HTML for one identifier.
   *
   * Any other route or method returns 404 with error HTML.
   *
   * @param {Request} request - Incoming HTTP request.
   * @param {Object} env - Worker bindings (R2 bucket, Durable Object and the
   *   injected VISUALIZER_CONFIG).
   * @param {Object} ctx - Execution context (waitUntil, ...).
   * @returns {Promise<Response>} Response with HTML, JSON or an error.
   */
  async fetch(request, env, ctx) {
    let effectiveEnv = env;
    if (!env.VISUALIZER_CONFIG && env.VARIABLES_KV) {
      try {
        const variables = await loadVariables(env);
        effectiveEnv = { ...env, VISUALIZER_CONFIG: variables.visualizer };
      } catch {
        effectiveEnv = env;
      }
    }

    const url = new URL(request.url);
    const path = url.pathname;

    // Unique CSP nonce per request (cryptographically secure).
    const nonce = generateNonce();

    console.log(JSON.stringify({ level: 'info', action: 'request_start', method: request.method, path }));

    // CORS preflight - answer OPTIONS immediately.
    if (request.method === 'OPTIONS') {
      try {
        const config = resolveVisualizerConfig(effectiveEnv);
        return addSecurityHeaders(
          addCorsHeaders(new Response(null, { status: 204 }), request, config),
          nonce,
        );
      } catch (error) {
        return handleRequestError(error, path, nonce, request, null);
      }
    }

    let config = null;

    try {
      let response;

      // Endpoint 1: JSON document list.
      if (path === LIST_PATH && request.method === 'GET') {
        config = resolveVisualizerConfig(effectiveEnv);
        response = await handleList(effectiveEnv, config);
      }
      // Endpoint 2: visualize one JSON document.
      else if (path.startsWith(OUTPUT_PATH_PREFIX) && request.method === 'GET') {
        const uuid = path.slice(OUTPUT_PATH_PREFIX.length);
        // Identifier allow list (defense in depth): prevents traversal ('/'),
        // broken selectors and injected HTML.
        if (!isValidIdentifier(uuid)) {
          response = new Response(render400HTML('El identificador del mapa no tiene un formato válido.'), {
            status: 400,
            headers: { 'Content-Type': 'text/html; charset=utf-8' }
          });
        } else {
          config = resolveVisualizerConfig(effectiveEnv);
          response = await handleVisualize(uuid, effectiveEnv, nonce, config, request);
        }
      }
      // 404 for unknown routes.
      else {
        response = new Response(render404HTML(path), {
          status: 404,
          headers: { 'Content-Type': 'text/html; charset=utf-8' }
        });
      }

      // Routes that do not require configuration (404 and invalid identifier)
      // still honor CORS when the configuration is available. A configuration
      // failure is not allowed to replace their intended status.
      if (!config) {
        try {
          config = resolveVisualizerConfig(effectiveEnv);
        } catch {
          config = null;
        }
      }

      // Add CORS and security headers to every response.
      return addSecurityHeaders(addCorsHeaders(response, request, config), nonce);

    } catch (error) {
      return handleRequestError(error, path, nonce, request, config);
    }
  }
};

/**
 * Builds the generic 500 response for an unexpected request failure.
 *
 * The error detail only goes to the structured log; the user receives a
 * generic message.
 *
 * @param {Error} error - Failure to log.
 * @param {string} path - Request path.
 * @param {string} nonce - Request CSP nonce.
 * @param {Request} request - Original request (used for CORS headers).
 * @param {Object|null} config - Validated configuration when it was already
 *   available, or null.
 * @returns {Response} Generic 500 HTML response with security headers.
 */
function handleRequestError(error, path, nonce, request, config) {
  console.error(JSON.stringify({
    level: 'error',
    action: 'request_error',
    path,
    error: error.message,
    code: error.code,
  }));

  const errorResponse = new Response(render500HTML(), {
    status: 500,
    headers: { 'Content-Type': 'text/html; charset=utf-8' }
  });

  return addSecurityHeaders(addCorsHeaders(errorResponse, request, config), nonce);
}

