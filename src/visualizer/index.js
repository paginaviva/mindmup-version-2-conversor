/**
 * Creates a coded configuration error.
 *
 * @param {string} code - Stable error code.
 * @param {string} message - Human-readable message.
 * @returns {Error} Error with a code property.
 */
function configError(code, message) {
  return Object.assign(new Error(message), { code });
}

/**
 * Checks whether a value is a non-null, non-array object.
 *
 * @param {*} value - Value to inspect.
 * @returns {boolean} true for plain objects.
 */
function isPlainObject(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * Reads a required non-empty string from the configuration.
 *
 * @param {Object} source - Configuration source.
 * @param {string} key - Required key.
 * @returns {string} The configured value.
 * @throws {Error} When the key is missing, empty or not a string.
 */
function readRequiredString(source, key) {
  const value = source[key];
  if (typeof value !== 'string' || value.trim() === '') {
    throw configError(
      'INVALID_VISUALIZER_CONFIG',
      `Configuración del visualizador no válida: "${key}" debe ser una cadena no vacía`,
    );
  }
  return value;
}

/**
 * Reads a required non-negative finite number from the configuration.
 *
 * @param {Object} source - Configuration source.
 * @param {string} key - Required key.
 * @returns {number} The configured value.
 * @throws {Error} When the key is missing, negative or not a finite number.
 */
function readNonNegativeNumber(source, key) {
  const value = source[key];
  if (typeof value !== 'number' || !Number.isFinite(value) || value < 0) {
    throw configError(
      'INVALID_VISUALIZER_CONFIG',
      `Configuración del visualizador no válida: "${key}" debe ser un número finito mayor o igual que 0`,
    );
  }
  return value;
}

/**
 * Reads a required array of strings from the configuration.
 *
 * An empty array is valid (no cross-origin caller is authorized).
 *
 * @param {Object} source - Configuration source.
 * @param {string} key - Required key.
 * @returns {string[]} The configured origins.
 * @throws {Error} When the key is missing, is not an array or contains a
 *   non-string entry.
 */
function readStringArray(source, key) {
  const value = source[key];
  if (!Array.isArray(value) || value.some((entry) => typeof entry !== 'string' || entry.trim() === '')) {
    throw configError(
      'INVALID_VISUALIZER_CONFIG',
      `Configuración del visualizador no válida: "${key}" debe ser un array de cadenas no vacías`,
    );
  }
  return [...value];
}

/**
 * Resolves and validates the visualizer runtime configuration.
 *
 * The configuration is injected through env.VISUALIZER_CONFIG, either as an
 * object or as a JSON string. Phase 3 builds this value from the KV documents;
 * this function does not read KV and does not provide silent defaults.
 *
 * Required keys:
 * - allowedOrigins: array of strings.
 * - outputPrefix: non-empty string (R2 storage prefix).
 * - jsonSuffix: non-empty string (JSON object suffix).
 * - listCacheSeconds: non-negative number.
 * - corsMaxAgeSeconds: non-negative number.
 * - durableObjectBinding: non-empty string (environment binding name).
 *
 * @param {Object} env - Worker environment.
 * @returns {Object} Validated configuration.
 * @throws {Error} MISSING_VISUALIZER_CONFIG when env or the configuration is
 *   missing.
 * @throws {Error} INVALID_VISUALIZER_CONFIG when the configuration is not a
 *   valid object or a required key is missing or has the wrong type.
 */
export function resolveVisualizerConfig(effectiveEnv) {
  if (!isPlainObject(effectiveEnv)) {
    throw configError(
      'MISSING_VISUALIZER_CONFIG',
      'Falta la configuración del visualizador: env.VISUALIZER_CONFIG',
    );
  }

  const raw = effectiveEnv.VISUALIZER_CONFIG;
  if (raw === undefined || raw === null) {
    throw configError(
      'MISSING_VISUALIZER_CONFIG',
      'Falta la configuración del visualizador: env.VISUALIZER_CONFIG',
    );
  }

  let source;
  if (typeof raw === 'string') {
    try {
      source = JSON.parse(raw);
    } catch {
      throw configError(
        'INVALID_VISUALIZER_CONFIG',
        'Configuración del visualizador no válida: env.VISUALIZER_CONFIG no contiene JSON válido',
      );
    }
  } else if (isPlainObject(raw)) {
    source = raw;
  } else {
    throw configError(
      'INVALID_VISUALIZER_CONFIG',
      'Configuración del visualizador no válida: env.VISUALIZER_CONFIG debe ser un objeto o una cadena JSON',
    );
  }

  if (!isPlainObject(source)) {
    throw configError(
      'INVALID_VISUALIZER_CONFIG',
      'Configuración del visualizador no válida: se esperaba un objeto JSON',
    );
  }

  return Object.freeze({
    allowedOrigins: readStringArray(source, 'allowedOrigins'),
    outputPrefix: readRequiredString(source, 'outputPrefix'),
    jsonSuffix: readRequiredString(source, 'jsonSuffix'),
    listCacheSeconds: readNonNegativeNumber(source, 'listCacheSeconds'),
    corsMaxAgeSeconds: readNonNegativeNumber(source, 'corsMaxAgeSeconds'),
    durableObjectBinding: readRequiredString(source, 'durableObjectBinding'),
  });
}

