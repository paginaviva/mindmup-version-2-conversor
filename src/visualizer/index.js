/**
 * @module index
 * Entry point of the visualizer Worker - HTTP router.
 *
 * Responsibilities:
 * 1. Default export with fetch(request, env, ctx).
 * 2. HTTP router for two endpoints:
 *    - GET /visor/api/lista -> lists the JSON documents in R2 with metadata.
 *    - GET /visor/mmup-output/{uuid} -> generates the HTML for one identifier.
 * 3. /visor/api/lista endpoint:
 *    - Runs R2.list() with the injected storage prefix.
 *    - Reads each JSON document to extract metadata (title, converted_at,
 *      node_count and source_file).
 *    - Sorts by converted_at descending (newest first).
 *    - Returns JSON: { success: true, count: N, items: [...] }.
 *    - Cache-Control duration comes from the injected configuration.
 * 4. /visor/mmup-output/{uuid} endpoint:
 *    - Gets the Durable Object stub from the injected binding name.
 *    - Calls the Durable Object with the internal /convert/{uuid} route.
 *    - Returns the HTML generated by the Durable Object.
 *    - Cache-Control: private, no-store (the HTML carries a per-request CSP
 *      nonce and must not be reused from shared caches).
 * 5. Error handling:
 *    - 404 when the identifier does not exist (propagated from the Durable
 *      Object).
 *    - 400 when the identifier does not satisfy the allow list or the JSON is
 *      invalid (propagated from the Durable Object).
 *    - 500 for internal failures, always with a generic message (details stay
 *      in the structured logs).
 *    - Uses the html-templates.js helpers for error HTML.
 * 6. Structured JSON logs for every operation.
 * 7. Security headers on every response (nosniff, no-referrer,
 *    X-Frame-Options: SAMEORIGIN) and a per-request CSP with a nonce for the
 *    viewer HTML; the nonce travels to the Durable Object through an internal
 *    header. SAMEORIGIN allows the authenticated upload preview to embed the
 *    viewer while blocking third-party framing.
 *
 * Configuration:
 * - All operational values (allowed origins, storage prefix, JSON suffix,
 *   cache durations and the Durable Object binding name) are injected through
 *   env.VISUALIZER_CONFIG.
 * - Phase 3 will populate env.VISUALIZER_CONFIG from the KV configuration and
 *   variables documents; this module intentionally does not read KV yet.
 * - Missing values fail explicitly with a coded error instead of silently
 *   falling back to defaults.
 */

import { render404HTML, render400HTML, render500HTML } from './utils/html-templates.js';
import { MupVisualizer, NONCE_HEADER, KEY_TEMPLATE_HEADER } from './mmup-visualizer-do.js';
import { loadVariables } from '../shared/config.js';
import { isValidIdentifier } from './utils/identifiers.js';

